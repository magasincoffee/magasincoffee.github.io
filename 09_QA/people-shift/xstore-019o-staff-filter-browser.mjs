import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const BASE=process.env.QA_BASE_URL||'http://127.0.0.1:8973';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1280,height:900}});
const errors=[];page.on('pageerror',e=>errors.push(String(e)));
try{
 await page.goto(BASE+'/09_QA/people-shift/manager-workforce-canonical-fixture.html',{waitUntil:'networkidle'});
 await page.locator('[data-view="staff"]').click();
 await page.locator('[data-msp-filter="ACTIVE"]').waitFor();
 assert.equal(await page.locator('[data-msp-edit]').count(),3);
 assert.equal(await page.locator('[data-msp-filter="ACTIVE"]').getAttribute('aria-pressed'),'true');
 await page.evaluate(()=>globalThis.__MW31_QA.setPersonStatus('u-2','INACTIVE'));
 await page.evaluate(()=>globalThis.MAGASIN_MANAGER_STAFF_PROJECTION.refresh());
 await page.locator('[data-msp-filter="ACTIVE"]').waitFor();
 assert.equal(await page.locator('[data-msp-edit]').count(),2);
 assert.match(await page.locator('.msp-filtertabs').innerText(),/Đang làm \(2\)/);
 assert.match(await page.locator('.msp-filtertabs').innerText(),/Đã nghỉ \/ Ngừng hoạt động \(1\)/);
 await page.locator('[data-msp-filter="INACTIVE"]').click();
 assert.equal(await page.locator('[data-msp-edit]').count(),1);
 assert.equal(await page.locator('[data-msp-edit]').first().getAttribute('data-msp-edit'),'u-2');
 await page.locator('[data-msp-edit="u-2"]').click();
 assert.equal(await page.locator('[data-msp-editor="u-2"]').count(),1);
 await page.locator('[data-msp-filter="ACTIVE"]').click();
 assert.equal(await page.locator('[data-msp-editor]').count(),0);
 await page.locator('[data-msp-filter="ALL"]').click();
 await page.locator('[data-msp-search]').fill('u-2');
 assert.equal(await page.locator('[data-msp-edit]').count(),1);
 await page.locator('[data-msp-search]').fill('no-match-employee');
 assert.equal(await page.locator('.msp-empty').count(),1);
 assert.equal(await page.locator('[data-msp-edit]').count(),0);
 await page.locator('[data-msp-search]').fill('');
 await page.evaluate(()=>{globalThis.__MW31_QA.people['u-2']=globalThis.__MW31_QA.people['u-1']});
 await page.evaluate(()=>globalThis.MAGASIN_MANAGER_STAFF_PROJECTION.refresh());
 await page.locator('[data-msp-filter="ALL"]').waitFor();
 const ids=await page.locator('[data-msp-edit]').evaluateAll(a=>a.map(x=>x.dataset.mspEdit));
 assert.deepEqual(ids.sort(),['u-1','u-2','u-3']);
 assert.deepEqual(errors,[]);
 console.log('XSTORE_019O_STAFF_FILTER_BROWSER=PASS');
}finally{await browser.close()}
