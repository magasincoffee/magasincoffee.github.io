-- Ephemeral-only PostgreSQL fixture for PR #503. NEVER APPLY TO PRODUCTION.
-- Synthetic UUIDs, no real employee records, no real Supabase service credentials.
CREATE ROLE anon NOLOGIN;
CREATE ROLE authenticated NOLOGIN;
CREATE ROLE qa_authenticator LOGIN NOINHERIT PASSWORD 'qa-local-disposable-password';
GRANT anon, authenticated TO qa_authenticator;
CREATE SCHEMA auth;
GRANT USAGE ON SCHEMA public TO anon, authenticated;
CREATE TABLE public.profiles(id uuid PRIMARY KEY,role text NOT NULL,status text NOT NULL);
CREATE TABLE public.stores(id uuid PRIMARY KEY,status text NOT NULL);
CREATE TABLE public.qa_manager_access(user_id uuid NOT NULL,store_id uuid NOT NULL);
CREATE TABLE public.employee_store_priorities(employee_id uuid NOT NULL,store_id uuid NOT NULL);
CREATE TABLE public.employee_availability(
 id uuid PRIMARY KEY,
 user_id uuid NOT NULL,
 work_date date NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now()
);
-- auth.uid reads PostgREST's *verified* JWT claims, not user_metadata.
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE SET search_path TO '' AS $$
 SELECT (nullif(current_setting('request.jwt.claims',true),'')::jsonb->>'sub')::uuid
$$;
CREATE FUNCTION public.current_user_role() RETURNS text LANGUAGE sql STABLE SET search_path TO '' AS $$
 SELECT p.role FROM public.profiles p WHERE p.id=auth.uid()
$$;
CREATE FUNCTION public.can_access_store(p_store_id uuid) RETURNS boolean
LANGUAGE sql STABLE SET search_path TO '' AS $$
 SELECT EXISTS (
   SELECT 1 FROM public.stores s WHERE s.id=p_store_id AND s.status='ACTIVE'
   AND (public.current_user_role()='OWNER'
     OR EXISTS (SELECT 1 FROM public.qa_manager_access a
       WHERE a.user_id=auth.uid() AND a.store_id=s.id))
 )
$$;
