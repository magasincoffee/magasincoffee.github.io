import assert from 'node:assert/strict';
import fs from 'node:fs';import path from 'node:path';import {chromium} from 'playwright';
const BASE=process.env.QA_BASE_URL||'http://127.0.0.1:8767',OUT=process.env.QA_OUT||'qa-artifacts/people-shift';
fs.mkdirSync(OUT,{recursive:true});const browser=await chromium.launch({headless:true});
try{
 for(const width of [1440,390]){
  const page=await browser.newPage({viewport:{width,height:900},timezoneId:'Asia/Ho_Chi_Minh'});
  const errors=[];page.on('pageerror',e=>errors.push(String(e)));
  await page.goto(BASE+'/09_QA/people-shift/manager-506-inline-coverage-fixture.html',{waitUntil:'networkidle'});
  const emit=async()=>{await page.evaluate(()=>window.__COVERAGE_487_QA.emit());await page.waitForTimeout(150)};
  const badge=()=>page.locator('[data-sv2-shortage-day="0"]');
  await page.waitForTimeout(150);
  assert.equal(await page.locator('#sv2Table').count(),1);
  assert.equal(await page.locator('#sv2CoverageTable,#sv2Coverage,[data-sv2-coverage-row],.sv2-roster-coverage-chip').count(),0,'no extra comparison UI or 238 slot chips');
  assert.equal(await badge().count(),0,'week 1 meets demand');
  await page.locator('#sv2Week').fill('2026-11-02');await emit();
  assert.equal(await badge().count(),1);
  assert.match(await badge().textContent(),/Thiếu tối đa 2 người/);
  assert.match(await badge().getAttribute('title'),/08:00–08:30: thiếu 2/);
  assert.equal(await badge().evaluate(el=>el.tagName),'DETAILS','shortage detail expands on touch, not title alone');
  assert.equal(await badge().locator('summary').count(),1);
  assert.equal(await badge().getAttribute('open'),null,'compact when first rendered');
  await badge().locator('summary').click();
  assert.notEqual(await badge().getAttribute('open'),null,'click opens exact shortage time ranges');
  assert.match(await badge().locator('.sv2-roster-shortage-times').textContent(),/08:00–08:30: thiếu 2 người/);
  await badge().locator('summary').press('Enter');
  assert.equal(await badge().getAttribute('open'),null,'keyboard toggles details closed');
  assert.equal(await page.locator('[data-sv2-shortage-day]').count(),1,'shortage belongs in the existing weekday header');
  await page.locator('#sv2Week').fill('2026-11-09');await emit();
  assert.equal(await badge().count(),0,'new week clears shortage');
  await page.locator('#sv2Store').selectOption('CN2');await emit();
  assert.equal(await badge().count(),0,'different branch keeps its own demand');
  await page.locator('#sv2Store').selectOption('CN1');
  await page.locator('#sv2Week').fill('2026-11-02');
  await page.evaluate(()=>{window.__COVERAGE_487_QA.stage='PUBLISHED';window.__COVERAGE_487_QA.emit()});await page.waitForTimeout(150);
  assert.equal(await badge().count(),1);
  assert.match(await badge().textContent(),/Thiếu tối đa 3 người/,'published shifts used');
  await page.locator('#sv2Store').selectOption('CNX');await emit();
  assert.equal(await badge().count(),0,'unauthorized scope cannot show old badge');
  await page.locator('#sv2Store').selectOption('CN1');
  await page.evaluate(()=>{window.__COVERAGE_487_QA.invalid=true;window.__COVERAGE_487_QA.emit()});await page.waitForTimeout(150);
  assert.equal(await badge().count(),0,'foreign record fails closed');
  await page.evaluate(()=>{window.__COVERAGE_487_QA.invalid=false;window.__COVERAGE_487_QA.error=true;window.__COVERAGE_487_QA.emit()});await page.waitForTimeout(150);
  assert.equal(await badge().count(),0,'network error never fabricates shortage');
  assert.deepEqual(errors,[]);
  await page.screenshot({path:path.join(OUT,'manager-506-roster-shortage-'+width+'.png'),fullPage:true});
  await page.close();
 }
 console.log('MANAGER_506_ROSTER_SHORTAGE_ONLY=PASS 1440/390; 3 weeks; branches; draft/published; no comparison UI');
}finally{await browser.close();}
