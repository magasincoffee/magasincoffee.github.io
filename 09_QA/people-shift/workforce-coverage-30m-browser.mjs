 assert.ok(first.includes('list_workforce_effective_weekly_staffing_v1')&&first.includes('read_adapter.week'));
 assert.ok(!first.some(x=>/replace|save|publish|update|insert/i.test(x)),'read-only RPC scope');
 await page.locator('#sv2Week').fill('2026-11-02');await page.evaluate(()=>window.__COVERAGE_487_QA.emit());await loaded();
